"""
One-command test of the parcel-fusion pipeline with dummy parcel vectors.

Run from the repository root with the meld_graph environment active:
    python scripts/classifier/test_parcel_fusion_pipeline.py
    python scripts/classifier/test_parcel_fusion_pipeline.py --vectors random     # random instead of zero vectors

Steps (stops at the first failure):
  1. writes one dummy parcel vector per subject, shape (2, 36), to <meld_data_path>/parcel_vectors_dummy
     (your real parcel_vectors folder is not touched)
  2. writes scripts/config_files/parcel_fusion_test.py: parcel_fusion_config.py with 1 epoch, the dummy folder
     and the experiment name H5_parcel_fusion_test/s_0
  3. runs the model unit tests (meld_graph/test/test_parcel_fusion.py)
  4. runs the input checks (check_parcel_fusion_inputs.py)
  5. trains 1 epoch (train_own_data.py)
  6. verifies: the fusion layers learned (scale moved away from 0) and the frozen encoder is unchanged
"""

import argparse
import glob
import os
import re
import subprocess
import sys

import numpy as np
import pandas as pd

from meld_graph.paths import BASE_PATH, EXPERIMENT_PATH, MELD_DATA_PATH

SOURCE_CONFIG = "scripts/config_files/parcel_fusion_config.py"
TEST_CONFIG = "scripts/config_files/parcel_fusion_test.py"
TEST_NAME = "H5_parcel_fusion_test/s_0"
DUMMY_DIR = os.path.join(MELD_DATA_PATH, "parcel_vectors_dummy")


def step(n, title):
    print(f"\n{'=' * 80}\nSTEP {n}: {title}\n{'=' * 80}", flush=True)


def run(cmd):
    print("$ " + " ".join(cmd), flush=True)
    result = subprocess.run(cmd)
    if result.returncode != 0:
        sys.exit(f"\nFAILED: {' '.join(cmd)} (exit code {result.returncode}). See the output above.")


def main():
    parser = argparse.ArgumentParser(description="Test the parcel-fusion pipeline with dummy parcel vectors")
    parser.add_argument("--vectors", choices=["zeros", "random"], default="zeros")
    parser.add_argument(
        "--demographics_csv",
        default=os.path.join(MELD_DATA_PATH, "my_data", "demographics_testbatch_meld.csv"),
    )
    parser.add_argument("--skip_unit_tests", action="store_true")
    args = parser.parse_args()

    if not os.path.isfile(SOURCE_CONFIG):
        sys.exit("Run this from the meld_graph repository root (scripts/config_files/parcel_fusion_config.py not found).")
    if not os.path.isfile(args.demographics_csv):
        sys.exit(f"Demographics CSV not found: {args.demographics_csv} (pass --demographics_csv)")
    source = open(SOURCE_CONFIG).read()

    # ---- 1. dummy parcel vectors
    step(1, f"dummy parcel vectors ({args.vectors}) -> {DUMMY_DIR}")
    match = re.search(r'"dataset":\s*"([^"]+)"', source)
    split_csv = os.path.join(BASE_PATH, match.group(1) if match else "split_testbatch.csv")
    ids = pd.read_csv(split_csv)["subject_id"].astype(str).tolist()
    match = re.search(r'^PARCEL_FILE_PATTERN = "([^"]+)"', source, flags=re.M)
    pattern = match.group(1) if match else "{subject_id}.npy"
    os.makedirs(DUMMY_DIR, exist_ok=True)
    for old in glob.glob(os.path.join(DUMMY_DIR, "*.npy")):  # remove dummies from earlier runs
        os.remove(old)
    rng = np.random.default_rng(0)
    for subject_id in ids:
        if args.vectors == "zeros":
            vec = np.zeros((2, 36), dtype=np.float32)
        else:
            vec = rng.normal(size=(2, 36)).astype(np.float32)
        if "{hemi}" in pattern:  # one file per hemisphere, shape (36,)
            for row, hemi in enumerate(("LH", "RH")):
                np.save(os.path.join(DUMMY_DIR, pattern.format(subject_id=subject_id, hemi=hemi)), vec[row])
        else:
            np.save(os.path.join(DUMMY_DIR, pattern.format(subject_id=subject_id)), vec)
    print(f"dummy files for {len(ids)} subjects written as {pattern} (subjects from {split_csv})")

    # ---- 2. test config
    step(2, f"test config -> {TEST_CONFIG}")
    test = source
    for pattern, replacement in (
        (r"^EXPERIMENT_NAME = .*$", f'EXPERIMENT_NAME = "{TEST_NAME}"'),
        (r"^N_EPOCHS = .*$", "N_EPOCHS = 1"),
        (r"^PARCEL_DIR = .*$", f'PARCEL_DIR = "{DUMMY_DIR}"'),
    ):
        test, n = re.subn(pattern, replacement, test, count=1, flags=re.M)
        if n != 1:
            sys.exit(f"Could not set '{replacement}' in {SOURCE_CONFIG}")
    with open(TEST_CONFIG, "w") as f:
        f.write("# generated by scripts/classifier/test_parcel_fusion_pipeline.py from parcel_fusion_config.py\n" + test)
    print("\n".join(line for line in test.splitlines() if re.match(r"^(EXPERIMENT_NAME|N_EPOCHS|PARCEL_DIR|BATCH_SIZE|FUSION_LEVELS) =", line)))

    # ---- 3. unit tests
    if args.skip_unit_tests:
        step(3, "model unit tests (skipped)")
    else:
        step(3, "model unit tests")
        run([sys.executable, "-m", "pytest", "meld_graph/test/test_parcel_fusion.py", "-q"])

    # ---- 4. input checks
    step(4, "input checks")
    run([sys.executable, "scripts/classifier/check_parcel_fusion_inputs.py", "--config_file", TEST_CONFIG])

    # ---- 5. training
    step(5, "train 1 epoch")
    run([
        sys.executable, "scripts/classifier/train_own_data.py",
        "--config_file", TEST_CONFIG,
        "--demographics_csv", args.demographics_csv,
    ])

    # ---- 6. verify
    step(6, "verify fusion learned and encoder stayed frozen")
    import torch

    from meld_graph.paths import load_config

    cfg = load_config(TEST_CONFIG)
    tp = cfg.network_parameters["training_parameters"]
    out_dir = os.path.join(EXPERIMENT_PATH, TEST_NAME, "fold_%02d" % cfg.data_parameters["fold_n"])
    trained = torch.load(os.path.join(out_dir, "final_model.pt"), map_location="cpu")
    pretrained = torch.load(os.path.join(EXPERIMENT_PATH, tp["init_weights"]), map_location="cpu")
    prefix = f"models.{tp['init_weights_ensemble_member']}." if any(k.startswith("models.") for k in pretrained) else ""

    scales = {k: trained[k].abs().mean().item() for k in sorted(trained) if k.endswith(".scale")}
    print("fusion scale per level (0 = fusion not used):")
    for k, v in scales.items():
        print(f"  {k}: {v:.3e}")
    encoder_keys = [k for k in trained if k.startswith("encoder_conv_layers.")]
    encoder_change = max((trained[k] - pretrained[prefix + k]).abs().max().item() for k in encoder_keys)
    print(f"encoder: largest change vs pretrained fold model = {encoder_change}")

    problems = []
    if not scales:
        problems.append("no parcel_fusion.*.scale weights in the trained model")
    elif not any(v > 0 for v in scales.values()):
        problems.append("all fusion scales are still 0 - the fusion layers did not train")
    if encoder_change != 0:
        problems.append("the encoder changed although it should be frozen")
    if problems:
        sys.exit("\nFAILED: " + "; ".join(problems))
    print(f"\nPARCEL FUSION PIPELINE TEST PASSED. Outputs in {out_dir}")


if __name__ == "__main__":
    main()
